export const i18n = createI18n({
  legacy: false,
  globalInjection: true,
  locale: readLocale(),
  fallbackLocale: "en",
  messages,
  missingWarn: false,
  fallbackWarn: false,
});

export function setAppLocale(locale: AppLanguage) {
  i18n.global.locale.value = locale;
  try {
    uni.setStorageSync(LOCALE_KEY, locale);
  } catch {
    // Locale remains active for the current session.
  }
}

export function getAppLocale(): AppLanguage {
  return i18n.global.locale.value === "zh-CN" ? "zh-CN" : "en";
}

export function translate(key: string, values?: Record<string, unknown>) {
  return values ? i18n.global.t(key, values) : i18n.global.t(key);
}
